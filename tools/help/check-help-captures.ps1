#requires -Version 7.0
<#
.SYNOPSIS
    The freshness gate of the help screenshots (S0032, CONTEXT-HELP section 4 rung 2, static form of 0.2 item D):
    is every picture on a help page still a picture of the screen it shows, and is every part the page names either
    pinned on it or recorded as absent.

.DESCRIPTION
    Reads (never writes, except with -WriteBaseline the one baseline file):
      tools/help/captures/captures.json          the capture records written by capture-help.ps1
      tools/help/captures/<page>/<locale>-<theme>.png   the committed images
      tools/help/captures/absent-baseline.json   the parts accepted as not shown (a baseline that may only fall)
      tools/help/capture-recipes.json            what each capture could show (its inputs) and how it is taken
      the files those inputs name: layouts, menus, drawables, colors, dimensions, themes and the strings of the
      locale for the phone; the Compose UI sources and the same resources for the watch
      gradle.properties                          the build sentinel version, which no record may carry

    States and exits:
      no record at all   rung 2 is NOT HELD: the device run of capture-help.ps1 is owed. Exit 0, the verdict line says
                         NOT HELD; with -Require (the release start) exit 1.
      records present    exit 1 on any of: a page or a locale without a record, a record that is malformed or names an
                         element the page lacks, a missing, altered or wrongly sized image, a record older than any of its
                         inputs (a change to a screen's resources or to a string of its locale after the capture), a record
                         carrying the build sentinel as its version, a version other than -ExpectVersion, a part recorded as
                         absent that the baseline does not accept, a baseline entry that is shown now.
      could not run      exit 2 (a required file is missing or unreadable).

    A stale record is cleared by running capture-help.ps1 again on a device. The baseline is regenerated by
    -WriteBaseline, never edited: it is written when it does not exist yet, or when the new set is inside the old one; a
    set that grows is refused.

    The last line written to stdout is the verdict line, `help-captures: ...`.

.PARAMETER Root
    Repository root. Defaults to two levels above this script; the self-test passes a throw-away tree.

.PARAMETER Require
    Treat "no record" as a failure (the release start).

.PARAMETER ExpectVersion
    Fail when a record was captured against another version (the release: the version name the pin printed).

.PARAMETER WriteBaseline
    Write absent-baseline.json from the records (first adoption, or a shrink).
#>
[CmdletBinding(PositionalBinding = $false)]
param(
    [string] $Root = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path,
    [switch] $Require,
    [string] $ExpectVersion = '',
    [switch] $WriteBaseline
)

$ErrorActionPreference = 'Stop'
trap {
    Write-Host "check-help-captures: could not run: $($_.Exception.Message)" -ForegroundColor Red
    Write-Host 'help-captures: COULD NOT VERIFY (a required input is missing or unreadable)'
    exit 2
}

. (Join-Path $PSScriptRoot '_help.ps1')

$mismatches = [System.Collections.Generic.List[string]]::new()
function Add-Mismatch { param([string] $Text) $mismatches.Add($Text) }

$map = Get-HelpMap -Root $Root
$pages = Get-HelpPageSources -Root $Root -Map $map
$recipes = Read-CaptureRecipes -Root $Root
$records = Read-CaptureRecords -Root $Root

if ($recipes.schemaVersion -ne 1) { throw "capture-recipes.json: schemaVersion is '$($recipes.schemaVersion)', the gate reads 1" }
foreach ($pageId in $pages.Keys) {
    if (-not $recipes.pages.ContainsKey($pageId)) { Add-Mismatch "capture-recipes.json has no recipe for page '$pageId'" }
}
foreach ($pageId in $recipes.pages.Keys) {
    if (-not $pages.Contains($pageId)) { Add-Mismatch "capture-recipes.json has a recipe for '$pageId', which is not a page of the help map" }
}

$baselinePath = Join-Path $Root $script:CaptureBaselineRelative
$baseline = @{}
if (Test-Path -LiteralPath $baselinePath) {
    $loaded = Read-HelpJson $baselinePath
    if ($loaded.schemaVersion -ne 1) { throw "absent-baseline.json: schemaVersion is not 1" }
    foreach ($pageId in $loaded.absent.Keys) {
        foreach ($locale in $loaded.absent[$pageId].Keys) { $baseline["$pageId/$locale"] = @($loaded.absent[$pageId][$locale] | ForEach-Object { [string]$_ }) }
    }
}

if ($null -eq $records) {
    if ($WriteBaseline) { throw 'There is no captures.json to write a baseline from' }
    $needed = 0
    foreach ($pageId in $pages.Keys) { $needed += @($recipes.pages[$pageId].themes).Count * $script:HelpLocales.Count }
    foreach ($line in $mismatches) { Write-Host $line -ForegroundColor Red }
    if ($mismatches.Count -gt 0) {
        Write-Host "help-captures: FAIL ($($mismatches.Count) mismatch(es))"
        exit 1
    }
    if ($Require) {
        Write-Host "help-captures: FAIL (no capture record; $needed image(s) are owed by the device run of tools/help/capture-help.ps1)"
        exit 1
    }
    Write-Host "help-captures: NOT HELD (no capture record; $needed image(s) are owed by the device run of tools/help/capture-help.ps1; rung 2 is not claimed)"
    exit 0
}

foreach ($problem in (Test-CaptureRecords -Root $Root -Pages $pages -Records $records)) { Add-Mismatch "record: $problem" }

$sentinel = ''
$propertiesPath = Join-Path $Root 'gradle.properties'
if (Test-Path -LiteralPath $propertiesPath) {
    $line = Get-Content -LiteralPath $propertiesPath | Where-Object { $_ -match '^\s*deviceinfo\.sentinel\.versionName\s*=' } | Select-Object -First 1
    if ($line) { $sentinel = ($line -split '=', 2)[1].Trim() }
}

$held = 0
$absentNow = @{}
foreach ($pageId in $pages.Keys) {
    foreach ($locale in $script:HelpLocales) {
        $tag = "$pageId/$locale"
        if (-not ($records.records.ContainsKey($pageId) -and $records.records[$pageId].ContainsKey($locale))) {
            Add-Mismatch "missing: no capture record for $tag (run tools/help/capture-help.ps1 on a device)"
            continue
        }
        $record = $records.records[$pageId][$locale]
        $recipe = $recipes.pages[$pageId]
        if (@($record.themes).Count -ne @($recipe.themes).Count -or @($record.themes | Where-Object { $_ -notin @($recipe.themes) }).Count -gt 0) {
            Add-Mismatch "$tag was captured in themes '$(@($record.themes) -join ',')', the recipe asks for '$(@($recipe.themes) -join ',')'"
        }
        $current = Get-CaptureInputHash -Root $Root -Recipe $recipe -Locale $locale
        if ($current.Hash -ne [string]$record.inputsHash) {
            Add-Mismatch "stale: $tag was captured on $($record.date) and an input has changed since ($($current.Count) inputs: layouts, menus, drawables, colors, dimensions, themes and strings of the screen's module, or the recipe); run tools/help/capture-help.ps1 on a device"
        }
        if ($sentinel -ne '' -and [string]$record.version -eq $sentinel) {
            Add-Mismatch "version: $tag carries the build sentinel $sentinel; capture against the pinned version with -ProductVersion"
        }
        if ($ExpectVersion -ne '' -and [string]$record.version -ne $ExpectVersion) {
            Add-Mismatch "version: $tag was captured against $($record.version), expected $ExpectVersion"
        }
        $absent = @($record.absent | ForEach-Object { [string]$_ } | Sort-Object)
        $absentNow[$tag] = $absent
        $accepted = if ($baseline.ContainsKey($tag)) { @($baseline[$tag]) } else { @() }
        if (-not $WriteBaseline) {
            foreach ($id in $absent) {
                if ($id -notin $accepted) { Add-Mismatch "absent: $tag does not show element '$id' and the baseline does not accept it (CONTEXT-HELP 0.2 item C); fix the layout or the recipe, or accept it with -WriteBaseline on the first adoption only" }
            }
            foreach ($id in $accepted) {
                if ($id -notin $absent) { Add-Mismatch "baseline: $tag lists '$id' as absent, but it is shown now; run -WriteBaseline to shrink the baseline" }
            }
        }
        $held++
    }
}

if ($WriteBaseline) {
    $grown = [System.Collections.Generic.List[string]]::new()
    if (Test-Path -LiteralPath $baselinePath) {
        foreach ($tag in $absentNow.Keys) {
            $accepted = if ($baseline.ContainsKey($tag)) { @($baseline[$tag]) } else { @() }
            foreach ($id in $absentNow[$tag]) { if ($id -notin $accepted) { $grown.Add("$tag`: '$id'") } }
        }
    }
    if ($grown.Count -gt 0) {
        foreach ($entry in $grown) { Write-Host "baseline would grow: $entry" -ForegroundColor Red }
        Write-Host "help-captures: FAIL (the baseline may only fall; $($grown.Count) new absent element(s))"
        exit 1
    }
    $tree = [ordered]@{}
    foreach ($tag in ($absentNow.Keys | Sort-Object)) {
        if ($absentNow[$tag].Count -eq 0) { continue }
        $pageId, $locale = $tag -split '/', 2
        if (-not $tree.Contains($pageId)) { $tree[$pageId] = [ordered]@{} }
        $tree[$pageId][$locale] = @($absentNow[$tag])
    }
    $json = ([ordered]@{ schemaVersion = 1; absent = $tree } | ConvertTo-Json -Depth 6)
    [System.IO.File]::WriteAllText($baselinePath, $json.Replace("`r`n", "`n") + "`n", [System.Text.UTF8Encoding]::new($false))
    Write-Host "help-captures: baseline written ($(@($tree.Keys).Count) page(s) with absent elements)"
    exit 0
}

if ($mismatches.Count -gt 0) {
    foreach ($line in $mismatches) { Write-Host $line -ForegroundColor Red }
    Write-Host "help-captures: FAIL ($($mismatches.Count) mismatch(es))"
    exit 1
}
Write-Host "help-captures: PASS ($held record(s) current, rung 2 held in the static form)"
exit 0
